struct KnowledgeArticle: Identifiable, Hashable {
    let id: String
    let title: String
    let summary: String       // 列表卡片摘要
    let duration: String      // "阅读时长 2分钟"
    let paragraphs: [String]  // 展开页正文段落
    let source: String        // 展开页「知识出处」
}

struct KnowledgeCategory: Identifiable, Hashable {
    var id: String { name }
    let name: String
    let articles: [KnowledgeArticle]
}

enum KnowledgeLibrary {
    static let categories: [KnowledgeCategory] = [
        bodyAndEmotion,
        emotionFirstAid,
        relationships,
        selfGrowth,
    ]

    /// 全部文章扁平列表，用于按 id 查找。
    static let allArticles: [KnowledgeArticle] = categories.flatMap(\.articles)

    /// 按 id 查找文章。id 来自 `KnowledgeArticle.id`(列表跳转)或 `defaultArticleId`,
    /// 生产路径恒为合法值;传入未知 id 属编程错误,直接 fail-fast 暴露而非静默降级。
    static func article(for id: String) -> KnowledgeArticle {
        guard let found = allArticles.first(where: { $0.id == id }) else {
            preconditionFailure("KnowledgeLibrary: unknown article id '\(id)'")
        }
        return found
    }

